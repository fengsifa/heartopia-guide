function lookup(locale, key) {
  const tree = ui[locale] || ui.en;
  return key.split('.').reduce(function (node, part) {
    if (node && typeof node === 'object' && part in node) return node[part];
    return undefined;
  }, tree);
}

/** 取整棵文案子树，页面里直接用 copy.xxx 更省事 */
export function dict(locale) {
  return ui[locale] || ui.en;
}

/** 取单个文案，支持 {var} 插值；缺失时回退到英文，再回退到 key 本身 */
export function t(locale, key, vars) {
  let value = lookup(locale, key);
  if (value === undefined) value = lookup('en', key);
  if (value === undefined) return key;
  if (typeof value !== 'string') return value;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, function (match, name) {
    return Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match;
  });
}
